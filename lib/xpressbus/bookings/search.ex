defmodule Xpressbus.Bookings.Search do
  @moduledoc """
  Database-backed bus search used by the results page.

  Besides the usual hygiene filters (legacy fallback rows, sold-out buses,
  buses from unapproved operators), results pass through
  `Xpressbus.Bookings.DepartureWindow`, which hides trips departing less than
  2 hours from now in Kenya time so users cannot select a bus they can no
  longer realistically catch.
  """

  import Ecto.Query

  alias Xpressbus.Bookings.{Bus, DepartureWindow}
  alias Xpressbus.Repo

  @doc """
  Returns bookable buses for `from` -> `to` on `travel_date`, ordered by
  departure time.

  `opts` are forwarded to `DepartureWindow.filter_bookable/3` (tests inject
  `:now`). An invalid date returns `[]`.
  """
  @spec list_bookable(String.t(), String.t(), Date.t() | String.t(), keyword()) :: [Bus.t()]
  def list_bookable(from, to, travel_date, opts \\ []) do
    case Date.from_iso8601(to_string(travel_date)) do
      {:ok, date} ->
        from
        |> query(to, date)
        |> Repo.all()
        |> DepartureWindow.filter_bookable(date, opts)

      _ ->
        []
    end
  end

  defp query(from, to, date) do
    from(b in Bus,
      left_join: operator in assoc(b, :bus_operator),
      where: b.from == ^from and b.to == ^to and b.travel_date == ^date,
      # Ignore rows generated by the old fallback scraper and sold-out buses.
      where: is_nil(b.source) or b.source != "legacy_fallback",
      where: b.seats != "0 seats left",
      # Buses submitted by partners stay hidden until the operator is approved.
      where: is_nil(operator.id) or operator.active == true,
      order_by: [asc: b.departure],
      preload: [:bus_operator]
    )
  end
end
