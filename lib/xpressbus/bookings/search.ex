defmodule Xpressbus.Bookings.Search do
  @moduledoc """
  The single source of truth for public bus visibility and search.

  Every public surface that exposes buses must use these functions (or
  `base_query/0`) so the rules cannot drift between the booking search, the
  cached BuuPass fallback, city pages, operator pages and SEO route discovery:

    * `legacy_fallback` rows are never public;
    * sold-out buses (`"0 seats left"`) are never public;
    * buses belonging to a partner operator are hidden until that operator is
      approved (`bus_operators.active == true`);
    * dated search results additionally pass through
      `Xpressbus.Bookings.DepartureWindow`, which hides trips departing less
      than 2 hours from now (Kenya time).
  """

  import Ecto.Query

  alias Xpressbus.Bookings.{Bus, DepartureWindow}
  alias Xpressbus.Repo

  @doc """
  Composable query with the public bus visibility rules.

  Use this as the source for every public listing/search query, e.g.

      from(b in Search.base_query(), where: b.from == ^city, select: b)

  Adding joins/selects with `from/2` is supported. Admin screens that must show
  every row should keep querying `Xpressbus.Bookings.Bus` directly.
  """
  @spec base_query() :: Ecto.Query.t()
  def base_query do
    from(b in Bus,
      left_join: operator in assoc(b, :bus_operator),
      # Ignore rows generated by the old fallback scraper.
      where: is_nil(b.source) or b.source != "legacy_fallback",
      # Hide sold-out buses (nil seat text is treated as available).
      where: is_nil(b.seats) or b.seats != "0 seats left",
      # Buses submitted by partners stay hidden until the operator is approved.
      where: is_nil(operator.id) or operator.active == true
    )
  end

  @doc """
  Returns bookable buses for `from` -> `to` on `travel_date`, ordered by
  departure time.

  Applies `base_query/0`, then hides departures inside the 2-hour window via
  `DepartureWindow.filter_bookable/3`. `opts` are forwarded to the window
  filter (tests inject `:now`). An invalid date returns `[]`.
  """
  @spec list_bookable(String.t(), String.t(), Date.t() | String.t(), keyword()) :: [Bus.t()]
  def list_bookable(from, to, travel_date, opts \\ []) do
    case Date.from_iso8601(to_string(travel_date)) do
      {:ok, date} ->
        from
        |> dated_query(to, date)
        |> Repo.all()
        |> DepartureWindow.filter_bookable(date, opts)

      _ ->
        []
    end
  end

  @doc """
  All `base_query/0` buses for a route/date (no departure-window filter).

  Only for summary/SEO use cases that need raw route inventory; public search
  results should call `list_bookable/4`.
  """
  @spec list_route_inventory(String.t(), String.t(), Date.t() | String.t()) :: [Bus.t()]
  def list_route_inventory(from, to, travel_date) do
    case Date.from_iso8601(to_string(travel_date)) do
      {:ok, date} -> from |> dated_query(to, date) |> Repo.all()
      _ -> []
    end
  end

  defp dated_query(from, to, date) do
    from(b in base_query(),
      where: b.from == ^from and b.to == ^to and b.travel_date == ^date,
      order_by: [asc: b.departure],
      preload: [:bus_operator]
    )
  end
end
